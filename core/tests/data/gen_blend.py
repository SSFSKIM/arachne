"""Write blend.txt: how Cairo's ARGB32 image surface blends one fill over a pixel, as CE draws.

The core's ``composite.rs`` blends 2D paint with Cairo's arithmetic and is tested against these
bytes. Run from an environment with pycairo installed::

    python core/tests/data/gen_blend.py > core/tests/data/blend.txt

Each line is ``blend r g b a  b0 b1 b2 b3  coverage -> o0 o1 o2 o3``: a fill colour as CE hands it
to Cairo (straight alpha, channels in CE's order; CE swaps red and blue for Cairo, so the bytes
land in memory as R, G, B, A), the pixel's bytes before the fill (CE writes its background
straight, so they need not be valid premultiplied colour), Cairo's 8-bit coverage of the pixel,
and the pixel's bytes after. Coverage is set exactly by filling a rectangle ``coverage / 256`` of a
pixel wide, which Cairo rasterizes as a box with that coverage. A second group fills a triangle
(Cairo's general scan converter); its coverage is read back from an opaque white fill over
opaque black, which leaves the coverage byte in every colour channel.
"""

from __future__ import annotations

import random

import cairo
import numpy as np

WIDTH = 8


def fill(rgba, background, path):
    pixels = np.zeros((1, WIDTH, 4), dtype=np.uint8)
    pixels[:, :] = background
    surface = cairo.ImageSurface.create_for_data(pixels, cairo.FORMAT_ARGB32, WIDTH, 1)
    ctx = cairo.Context(surface)
    ctx.set_source_rgba(rgba[2], rgba[1], rgba[0], rgba[3])
    path(ctx)
    ctx.fill()
    surface.flush()
    return pixels[0]


def box(coverage):
    def path(ctx):
        ctx.rectangle(0, 0, coverage / 256, 1)

    return path


def triangle(ctx):
    ctx.move_to(0.0, 0.0)
    ctx.line_to(WIDTH, 0.37)
    ctx.line_to(0.21, 1.0)
    ctx.close_path()


def line(rgba, background, coverage, out):
    numbers = [*(repr(float(c)) for c in rgba), *(str(int(b)) for b in background)]
    print("blend", *numbers, coverage, "->", *(int(o) for o in out))


def colours(rng, n):
    for i in range(n):
        rgba = [rng.random() for _ in range(4)]
        if i % 3 == 0:
            rgba[3] = 1.0  # Cairo blends an opaque colour another way (a lerp)
        if i % 7 == 0:
            rgba[3] = 0.0
        if i % 11 == 0:
            rgba[0] = 1.0
        background = [rng.randrange(256) for _ in range(3)]
        background.append(rng.choice([255, 255, 255, 200, 76, 0]))
        yield rgba, background


def main():
    rng = random.Random(0)
    print("# Generated by gen_blend.py from Cairo's ARGB32 image surface. Do not edit.")
    print(f"# cairo {cairo.cairo_version_string()}")
    for rgba, background in colours(rng, 120):
        for coverage in (rng.choice([1, 2, 17, 64, 127, 128, 129, 200, 254]), 255, 256):
            out = fill(rgba, background, box(coverage))[0]
            line(rgba, background, min(coverage, 255), out)
    white = fill([1.0, 1.0, 1.0, 1.0], [0, 0, 0, 255], triangle)
    coverages = [int(px[0]) for px in white]
    assert all(px[0] == px[1] == px[2] for px in white)
    for rgba, background in colours(rng, 40):
        out = fill(rgba, background, triangle)
        for coverage, px in zip(coverages, out, strict=True):
            if coverage:
                line(rgba, background, coverage, px)


if __name__ == "__main__":
    main()
