"""Write gradient.txt: the pixels Cairo's ARGB32 image surface paints when CE fills a path with a
linear gradient (``Camera.set_cairo_context_color`` with two or more colours).

The core's ``gradient.rs`` follows Cairo's pattern and pixman's fetch and is tested against these
bytes. Run from an environment with pycairo installed::

    python core/tests/data/gen_gradient.py > core/tests/data/gradient.txt

Each case fills a pixel-aligned rectangle on a fresh surface, so every pixel of a row is fetched
in one composite run starting at the rectangle's left edge, and (the surface being clear) holds
exactly the premultiplied colour pixman fetched. Lines:

- ``case pw ph cx cy  p1x p1y p2x p2y  x y w h  n``: the frame in pixels and the centre CE's context
  maps around (its matrix is ``Camera.make_cairo_context``'s, for a frame 14.22 by 8 units), the
  gradient's ends in frame units, the rectangle in pixels;
- ``stop r g b a``, ``n`` of them: the colours as CE hands them (straight, channels in CE's
  order, some beyond 0..1 as CE's lighting makes them; Cairo clamps), at ``np.linspace(0, 1, n)``;
- ``px x y -> o0 o1 o2 o3``: a pixel's bytes, in memory order (R, G, B, A, since CE swaps red
  and blue for Cairo).
"""

from __future__ import annotations

import random

import cairo
import numpy as np


def main() -> None:
    rng = random.Random(20261105)
    print(
        "# Generated by gen_gradient.py from Cairo's ARGB32 image surface. Do not edit."
    )
    print(f"# cairo {cairo.cairo_version_string()}")
    for _ in range(24):
        pw = rng.choice([192, 480, 854, 1280, 1920])
        ph = pw * 9 // 16
        fw, fh = 14.222222222222221, 8.0
        fc = (rng.uniform(-1, 1), rng.uniform(-1, 1))
        ctm = (
            pw / fw,
            0.0,
            0.0,
            -(ph / fh),
            (pw / 2) - fc[0] * (pw / fw),
            (ph / 2) + fc[1] * (ph / fh),
        )
        w = rng.randint(8, min(400, pw - 2))
        h = rng.randint(4, min(60, ph - 2))
        x0 = rng.randint(0, pw - w)
        y0 = rng.randint(0, ph - h)
        inv = cairo.Matrix(*ctm)
        inv.invert()
        corners = [
            inv.transform_point(x, y)
            for x, y in ((x0, y0), (x0 + w, y0), (x0 + w, y0 + h), (x0, y0 + h))
        ]
        ux = [c[0] for c in corners]
        uy = [c[1] for c in corners]
        span = max(max(ux) - min(ux), max(uy) - min(uy))
        p1 = (rng.uniform(min(ux), max(ux)), rng.uniform(min(uy), max(uy)))
        p2 = (p1[0] + rng.uniform(-span, span), p1[1] + rng.uniform(-span, span))
        n = rng.choice([2, 2, 2, 3, 4])
        opaque = rng.random() < 0.6
        rgbas = [
            (
                rng.uniform(-0.2, 1.3),
                rng.uniform(0, 1),
                rng.uniform(0, 1),
                1.0 if opaque else rng.uniform(0.05, 1),
            )
            for _ in range(n)
        ]
        surface = cairo.ImageSurface(cairo.FORMAT_ARGB32, pw, ph)
        ctx = cairo.Context(surface)
        ctx.set_matrix(cairo.Matrix(*ctm))
        for i, c in enumerate(corners):
            (ctx.move_to if i == 0 else ctx.line_to)(*c)
        ctx.close_path()
        pattern = cairo.LinearGradient(p1[0], p1[1], p2[0], p2[1])
        for rgba, offset in zip(rgbas, np.linspace(0, 1, n), strict=True):
            pattern.add_color_stop_rgba(offset, rgba[2], rgba[1], rgba[0], rgba[3])
        ctx.set_source(pattern)
        ctx.fill()
        surface.flush()
        data = np.ndarray((ph, pw, 4), np.uint8, surface.get_data())
        print("case", pw, ph, *map(repr, fc), *map(repr, (*p1, *p2)), x0, y0, w, h, n)
        for rgba in rgbas:
            print("stop", *map(repr, rgba))
        for _ in range(40):
            x = rng.randrange(x0, x0 + w)
            y = rng.randrange(y0, y0 + h)
            print("px", x, y, "->", *(int(v) for v in data[y, x]))


if __name__ == "__main__":
    main()
