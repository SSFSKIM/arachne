"""Write projection.txt: CE's camera maths evaluated by Arachne's own camera classes.

The core's ``project.rs`` is tested against these values. Run from an environment with Arachne
installed::

    python core/tests/data/gen_projection.py > core/tests/data/projection.txt

Each line is a record name and numbers (``->`` separates inputs from outputs); floats are written
with ``repr``, which round-trips exactly.
"""

from __future__ import annotations

import math

import cairo
import numpy as np

from arachne.camera.camera import Camera
from arachne.camera.three_d_camera import ThreeDCamera
from arachne.mobject.mobject import Mobject

POINTS = [
    (0.0, 0.0, 0.0),
    (1.0, 2.0, 3.0),
    (-3.5, 0.25, -1.75),
    (4.0, -2.0, 0.5),
    (0.1, 0.2, -10.0),
    (2.0, 2.0, 7.0),
    (-1.0, 3.0, 4.999),
    (6.5, -3.25, 2.2),
    (-6.0, -3.0, 12.0),
    (0.0, 0.0, 19.9999),
    (1e-9, -1e-9, 1e-9),
    (3.0, 1.0, 30.0),
]

CAMERAS = [
    # name, phi, theta, gamma, focal distance, zoom, exponential, frame centre
    ("default", 0.0, -math.pi / 2, 0.0, 20.0, 1.0, False, (0.0, 0.0, 0.0)),
    (
        "tilted",
        70 * math.pi / 180,
        -45 * math.pi / 180,
        0.1,
        20.0,
        1.0,
        False,
        (0.5, -0.25, 0.0),
    ),
    (
        "exponential",
        75 * math.pi / 180,
        30 * math.pi / 180,
        -0.3,
        8.0,
        1.7,
        True,
        (1.0, 2.0, 3.0),
    ),
    ("small_phi", 0.0004, 1.0, 2.5, 12.0, 0.6, False, (0.0, 0.0, -1.0)),
    (
        "behind_eye",
        -2.0943951023931953,
        3.490658503988659,
        0.0,
        5.0,
        2.0,
        False,
        (0, 0, 0),
    ),
]

PIXELS = (854, 480)
FRAME = (14.222222222222221, 8.0)


def fmt(values) -> str:
    return " ".join(repr(float(v)) for v in np.ravel(values))


def device(ctx: cairo.Context, points: np.ndarray) -> list[tuple[float, float]]:
    return [ctx.user_to_device(float(p[0]), float(p[1])) for p in points]


def main() -> None:
    pts = np.array(POINTS, dtype=float)
    print(
        "# Generated by gen_projection.py from Arachne's Camera and ThreeDCamera. Do not edit."
    )
    for name, phi, theta, gamma, focal, zoom, exponential, centre in CAMERAS:
        cam = ThreeDCamera(
            pixel_width=PIXELS[0],
            pixel_height=PIXELS[1],
            frame_width=FRAME[0],
            frame_height=FRAME[1],
            frame_center=np.array(centre, dtype=float),
            exponential_projection=exponential,
        )
        cam.set_phi(phi)
        cam.set_theta(theta)
        cam.set_gamma(gamma)
        cam.set_focal_distance(focal)
        cam.set_zoom(zoom)
        cam.reset_rotation_matrix()
        print(
            "camera",
            name,
            fmt([phi, theta, gamma, focal, zoom, float(exponential)]),
            fmt(cam.frame_center),
            *PIXELS,
            # The camera's own frame size: CE fits the height to the pixels' aspect ratio.
            fmt([cam.frame_width, cam.frame_height]),
        )
        print("rotation", fmt(cam.get_rotation_matrix()))
        projected = cam.project_points(pts.copy())
        for p, q in zip(pts, projected, strict=True):
            print("project", fmt(p), "->", fmt(q))

        ctx = cam.get_cairo_context(np.zeros((PIXELS[1], PIXELS[0], 4), dtype=np.uint8))
        print("matrix", fmt(list(ctx.get_matrix())))
        for p, d in zip(pts, device(ctx, projected), strict=True):
            print("device", fmt(p), "->", fmt(d))

        cloud = Mobject()
        subpixel = cam.points_to_subpixel_coords(cloud, pts.copy())
        for p, s in zip(pts, subpixel, strict=True):
            print("subpixel", fmt(p), "->", fmt(s))

        for centre_point in [(1.0, -1.0, 2.0), (0.0, 0.0, -4.0)]:
            label = Mobject()
            cam.add_fixed_orientation_mobjects(
                label, center_func=lambda c=centre_point: np.array(c)
            )
            moved = cam.transform_points_pre_display(label, pts.copy())
            for p, q in zip(pts, moved, strict=True):
                print("fixed_orientation", fmt(centre_point), fmt(p), "->", fmt(q))

        title = Mobject()
        cam.add_fixed_in_frame_mobjects(title)
        kept = cam.transform_points_pre_display(title, pts.copy())
        for p, q in zip(pts, kept, strict=True):
            print("fixed_in_frame", fmt(p), "->", fmt(q))

        broken = np.array([[np.nan, 0.0, 0.0], [1.0, 2.0, 3.0]])
        print("nonfinite ->", fmt(cam.transform_points_pre_display(Mobject(), broken)))

    for centre in [(0.0, 0.0, 0.0), (1.5, -0.75, 2.0)]:
        cam = Camera(
            pixel_width=PIXELS[0],
            pixel_height=PIXELS[1],
            frame_width=FRAME[0],
            frame_height=FRAME[1],
            frame_center=np.array(centre, dtype=float),
        )
        print("flat", fmt(centre), *PIXELS, fmt([cam.frame_width, cam.frame_height]))
        ctx = cam.get_cairo_context(np.zeros((PIXELS[1], PIXELS[0], 4), dtype=np.uint8))
        print("matrix", fmt(list(ctx.get_matrix())))
        for p, d in zip(pts, device(ctx, pts), strict=True):
            print("device", fmt(p), "->", fmt(d))
        subpixel = cam.points_to_subpixel_coords(Mobject(), pts.copy())
        for p, s in zip(pts, subpixel, strict=True):
            print("subpixel", fmt(p), "->", fmt(s))


if __name__ == "__main__":
    main()
